/**
 * What a room game can be about. A category is a list of artists that belong
 * to it for sure: the game takes each one's most popular songs, keeping only
 * those really by that artist. Public playlists were tried first, but too many
 * mix in songs from anywhere. `suffix` narrows the search when an artist also
 * has songs outside the theme. Your own words (`customCategory`) still go
 * through searches.
 */
export type GameCategory = {
  id: string;
  name: string;
  icon: IconName;
  color: string;
  artists?: string[];
  suffix?: string;
  queries: string[];
};

